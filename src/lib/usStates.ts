const CODES = new Set(US_STATES.map((s) => s.code));
const BY_NAME = new Map(US_STATES.map((s) => [s.name.toLowerCase(), s.code]));

/**
 * Normalise whatever a form sent as "state" to a two-letter code when it can
 * be recognised ("wa" → "WA", "Washington" → "WA"); anything else is returned
 * trimmed so validation elsewhere can still reject or accept it.
 */
export function normalizeUsState(raw: string): string {
  const s = raw.trim();
  const upper = s.toUpperCase();
  if (CODES.has(upper)) return upper;
  return BY_NAME.get(s.toLowerCase()) ?? s;
}
